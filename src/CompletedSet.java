
public class CompletedSet {

	int repCount;
	int weight;
	
	public CompletedSet(int repCount, int weight) {
		setRepCount(repCount);
		setWeight(weight);
	}
	
	void setRepCount(int repCount) {
		this.repCount = repCount;
	}
	
	int getRepCount() {
		return repCount;
	}
	
	void setWeight(int weight) {
		this.weight = weight;
	}
	
	int getWeight() {
		return weight;
	}
	
	
	
}
